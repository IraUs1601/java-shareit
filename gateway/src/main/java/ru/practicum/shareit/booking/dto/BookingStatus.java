package ru.practicum.shareit.booking.dto;

/**
 * Статус бронирования.
 * <p>
 * Используется для отображения текущего состояния брони:
 * <ul>
 *     <li>{@link #WAITING} — ожидание подтверждения владельцем</li>
 *     <li>{@link #APPROVED} — подтверждено владельцем</li>
 *     <li>{@link #REJECTED} — отклонено владельцем</li>
 *     <li>{@link #CANCELED} — отменено пользователем</li>
 * </ul>
 */
public enum BookingStatus {
    /**
     * Бронирование ожидает подтверждения владельцем.
     */
    WAITING,

    /**
     * Бронирование подтверждено владельцем.
     */
    APPROVED,

    /**
     * Бронирование отклонено владельцем.
     */
    REJECTED,

    /**
     * Бронирование отменено пользователем.
     */
    CANCELED
}